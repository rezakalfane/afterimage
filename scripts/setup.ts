// npm run setup — idempotent local installation.
//   npm run setup                    asks: rehearsal (no account needed) or live Napster
//   npm run setup -- --mode=rehearsal|live   non-interactive
// Creates .env.local only if missing (local secrets generated here, never printed), the SQLite
// database, migrations, the public demo tenant and, if no owner exists yet, a one-time local
// owner invitation link. Never creates Napster resources (see `npm run provision:napster`).
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline/promises";
import { loadEnv, parseEnvFile } from "./lib/env-file";
import { applyMigrations, openClient, seed } from "./lib/db";
import { createBootstrapInvitation } from "./lib/bootstrap";

const secret = (n = 32) => randomBytes(n).toString("base64url");

async function chooseMode(): Promise<"rehearsal" | "live"> {
  const flag = process.argv.find((a) => a.startsWith("--mode="))?.split("=")[1];
  if (flag === "rehearsal" || flag === "live") return flag;
  if (!process.stdin.isTTY) return "rehearsal";
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const a = (await rl.question("Mode ? [1] Répétition locale (sans compte, défaut)  [2] Napster réel : ")).trim();
  rl.close();
  return a === "2" ? "live" : "rehearsal";
}

function napsterIds(): { jeanne?: string; malik?: string } {
  if (!existsSync("config/napster-resources.json")) return {};
  const r = JSON.parse(readFileSync("config/napster-resources.json", "utf8"));
  return { jeanne: r.agents?.jeanne?.fr, malik: r.agents?.malik?.fr };
}

async function main() {
  const [major, minor] = process.versions.node.split(".").map(Number);
  if (major < 22 || (major === 22 && minor < 12)) throw new Error(`Node ${process.versions.node} détecté : Node >= 22.12 requis.`);
  console.log(`✓ Node ${process.versions.node}`);

  if (!existsSync(".env.local")) {
    const mode = await chooseMode();
    const ids = napsterIds();
    const lines = [
      "# Generated by `npm run setup` — LOCAL ONLY. Never commit, never reuse on staging/production.",
      "APP_ENV=local",
      "APP_URL=http://localhost:3000",
      `BETTER_AUTH_SECRET=${secret()}`,
      `MEMORY_ID_SECRET=${secret()}`,
      `CRON_SECRET=${secret(24)}`,
      "DATABASE_URL=file:./var/afterimage.db",
      `CONVERSATION_MODE=${mode}`,
      "NAPSTER_MAX_ACTIVE=1",
      "NAPSTER_RECORDINGS_ENABLED=false",
      "NAPSTER_PHONE_ENABLED=false",
      ...(mode === "live" ? [`NAPSTER_JEANNE_AGENT_ID=${ids.jeanne ?? ""}`, `NAPSTER_MALIK_AGENT_ID=${ids.malik ?? ""}`] : []),
    ];
    writeFileSync(".env.local", lines.join("\n") + "\n", { mode: 0o600 });
    console.log(`✓ .env.local créé (mode ${mode === "live" ? "Napster réel" : "répétition"}, secrets générés localement)`);
    if (mode === "live" && !parseEnvFile(".env").NAPSTER_API_KEY && !process.env.NAPSTER_API_KEY) {
      console.log("  ! NAPSTER_API_KEY absent : ajoutez-le dans .env.local (jamais dans Git), puis `npm run doctor`.");
    }
  } else {
    console.log("✓ .env.local existe déjà — conservé tel quel");
  }

  loadEnv();
  const client = openClient(process.env.DATABASE_URL!, process.env.DATABASE_AUTH_TOKEN);
  if (!process.env.DATABASE_URL!.startsWith("file:")) throw new Error("setup est réservé à la base locale. Pour staging/production : npm run release:migrate.");
  await applyMigrations(client);
  console.log("✓ migrations appliquées");
  const s = await seed(client, process.env.PUBLIC_TENANT_SLUG ?? "demo");
  console.log(`✓ tenant de démonstration et épisode (${s.episode})`);

  const owners = await client.execute(`SELECT count(*) AS n FROM memberships WHERE role = 'owner'`);
  const pending = await client.execute({ sql: `SELECT count(*) AS n FROM invitations WHERE role = 'owner' AND consumed_at IS NULL AND expires_at > ?`, args: [Date.now()] });
  if (Number(owners.rows[0].n) > 0) {
    console.log("✓ owner déjà présent");
  } else if (Number(pending.rows[0].n) > 0) {
    console.log("✓ une invitation owner valide existe déjà (lien affiché lors du setup précédent).");
    console.log("  Nouveau lien si besoin : npm run ops:bootstrap-owner -- --email=vous@exemple.fr");
  } else if (process.stdin.isTTY) {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const email = (await rl.question("Email de l’owner (administration ; Entrée pour plus tard) : ")).trim();
    rl.close();
    if (/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) {
      console.log("✓ lien d’amorçage local à usage unique (24 h) — l’owner y choisit son mot de passe :");
      console.log(`  ${await createBootstrapInvitation(client, process.env.APP_URL!, email)}`);
    } else console.log("  Owner non créé. Plus tard : npm run ops:bootstrap-owner -- --email=vous@exemple.fr");
  } else {
    console.log("  Aucun owner (administration). Pour en créer un : npm run ops:bootstrap-owner -- --email=vous@exemple.fr");
  }
  client.close();
  console.log("\nPrêt. Lancez : npm run dev   puis ouvrez http://localhost:3000");
}

main().catch((e) => {
  console.error(`✗ ${e instanceof Error ? e.message : e}`);
  process.exit(1);
});
